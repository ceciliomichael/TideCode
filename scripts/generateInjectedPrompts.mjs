import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
const root = path.resolve(import.meta.dirname,'..')
const directory = path.join(root,'electron/chat/shared/ai/prompts/injected')
const names = [
 'agentMode','planMode','executionSandbox','executionFullAccess',
 'workspaceInstructions','workspaceInstructionsChanged','workspaceMemoryEnabled',
 'terminalEnvironment','terminalEnvironmentUnavailable',
 'pythonEnvironment','pythonEnvironmentUnavailable',
]
const templates = Object.fromEntries(await Promise.all(names.map(async name => {
 const content=(await readFile(path.join(directory,name+'.md'),'utf8')).trim()
 if(!content || content.includes('<hidden_user_context')) throw new Error('Invalid injected template '+name)
 return [name,content]
})))
const output = '// AUTO-GENERATED from electron/chat/shared/ai/prompts/injected/*.md.\n'
  + '// Edit Markdown and run npm run prompts:sync; do not edit this file.\n'
  + 'export const injectedPromptTemplates = '+JSON.stringify(templates,null,2)+' as const\n'
const destination = path.join(root, 'src/lib/generatedInjectedPrompts.ts')
const previous = await readFile(destination, 'utf8').catch(() => null)
if (previous !== output) {
  await writeFile(destination, output)
}
